<script>
(function () {
  var animated = false;

  function formatNum(n, target) {
    if (target >= 1000) {
      return n >= 1000 ? (n / 1000).toFixed(n % 1000 === 0 ? 0 : 0) + ',000' : n.toString();
    }
    return n.toString();
  }

  function runCountup() {
    if (animated) return;
    animated = true;
    var els = document.querySelectorAll('.stat-num');
    els.forEach(function (el) {
      var target = parseInt(el.getAttribute('data-target'), 10);
      var suffix = el.getAttribute('data-suffix') || '';
      var duration = 1600;
      var start = performance.now();
      var startVal = target > 1000 ? Math.round(target * 0.2) : 0;

      function step(now) {
        var elapsed = now - start;
        var progress = Math.min(elapsed / duration, 1);
        // ease out cubic
        var eased = 1 - Math.pow(1 - progress, 3);
        var current = Math.round(startVal + (target - startVal) * eased);
        el.textContent = formatNum(current, target) + suffix;
        if (progress < 1) requestAnimationFrame(step);
      }
      requestAnimationFrame(step);
    });
  }

  var observer = new IntersectionObserver(function (entries) {
    entries.forEach(function (entry) {
      if (entry.isIntersecting) runCountup();
    });
  }, { threshold: 0.3 });

  var statsEl = document.getElementById('aboutStats');
  if (statsEl) observer.observe(statsEl);
})();
</script>
