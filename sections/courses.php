<script>
document.querySelectorAll('#courses .course-card').forEach(function(card) {
  var icon = card.querySelector('.card-icon');
  if (!icon) return;
  var bg      = icon.dataset.bg;
  var color   = icon.dataset.color;
  var hoverBg = icon.dataset.hoverBg;
  card.addEventListener('mouseenter', function() {
    icon.style.backgroundColor = hoverBg;
    icon.style.color = '#fff';
  });
  card.addEventListener('mouseleave', function() {
    icon.style.backgroundColor = bg;
    icon.style.color = color;
  });
});
</script>
